/// The DNSCrypt proxy's config (build 2075). dnscrypt-proxy
/// (libdnscrypt.so, DnsCryptCore.kt) runs as a local
/// resolver on loopback; the Xray DNS settings gain a
/// "dnscrypt" transport whose resolver is this proxy
/// (config_builder's dnsCryptResolverAddress), so encrypted
/// DNS becomes one more transport next to DoH / DoQ /
/// DNS-over-TCP.
///
/// The config pins the well-known public resolver LIST
/// (the signed dnscrypt-resolvers v3 list, the upstream
/// default source and its long-standing minisign key) and
/// two named servers from it. The list itself downloads on
/// first use and is cached in the proxy's work dir; the
/// proxy's traffic leaves under the app UID, which the VPN
/// service excludes from the TUN.

/// The proxy's local listen port (mirrored in Kotlin:
/// DnsCryptCore.PORT, and in config_builder's
/// dnsCryptResolverAddress).
const dnsCryptListenPort = 20530;

/// The TOML for [workDir] (the proxy's filesDir/dnscrypt
/// directory, where its resolver-list cache lives).
String buildDnsCryptConfig(String workDir) =>
    '''
# Generated by Ralysnd Ember (build 2075) — the DNSCrypt
# transport's local resolver. Hand edits are overwritten
# at the next start.
listen_addresses = ['127.0.0.1:$dnsCryptListenPort']
server_names = ['cloudflare', 'quad9-dnscrypt-ip4-filter-pri']
ipv6_servers = false
require_dnssec = true
require_nolog = true
require_nofilter = true
cache = true
cache_size = 512

[sources]
  [sources.'public-resolvers']
  urls = ['https://raw.githubusercontent.com/DNSCrypt/dnscrypt-resolvers/master/v3/public-resolvers.md', 'https://download.dnscrypt.info/resolvers-list/v3/public-resolvers.md']
  cache_file = '$workDir/public-resolvers.md'
  minisign_key = 'RWQf6LRCGA9i53mlYecO4IzT51TGPpvWucNSCh1CBM0QTaLn73Y7G2'
  refresh_delay = 72
''';
